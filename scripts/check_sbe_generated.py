#!/usr/bin/env python3
"""Verify the checked-in SBE codec is reproducible from its schema sources.

Generation is deliberately outside the workspace build graph. This gate runs
the on-demand generator into a repository-local scratch directory and compares
its bytes with the checked-in module. No file outside this checkout is written.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / ".local" / "sbe-generated-check"
CHECKED_IN = ROOT / "src" / "generated" / "orderbook.rs"
MANIFEST = ROOT / "tools" / "sbe-gen" / "Cargo.toml"


def regenerate() -> str:
    """Run the generator and return its stdout for diagnostics."""
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [
            "cargo",
            "run",
            "--quiet",
            "--manifest-path",
            str(MANIFEST),
            "--",
            "--schema-root",
            str(ROOT),
            "--output",
            str(OUTPUT),
        ],
        cwd=ROOT,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(f"SBE generator failed: {detail}")
    return result.stdout.decode("utf-8", errors="replace").strip()


def main() -> int:
    """Fail closed when generated bytes drift from the schema."""
    try:
        regenerate()
        generated = (OUTPUT / "orderbook.rs").read_bytes()
        checked_in = CHECKED_IN.read_bytes()
    except (OSError, RuntimeError) as error:
        print(f"[FAIL] generated codec check could not run: {error}")
        return 1
    if generated != checked_in:
        print("[FAIL] checked-in SBE codec differs from schema regeneration")
        return 1
    print("[PASS] checked-in SBE codec matches schema regeneration")
    return 0


if __name__ == "__main__":
    sys.exit(main())
